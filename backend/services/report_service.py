from datetime import datetime, timezone
from database import get_database

async def generate_html_report(case_id: str, generated_by: str = "Forensic Examiner") -> str:
    """Generate an authoritative, standalone HTML forensic report for a case."""
    db = get_database()
    case = await db.cases.find_one({"case_id": case_id})
    if not case:
        raise ValueError(f"Case {case_id} not found")

    devices = await db.devices.find({"case_id": case_id}).to_list(100)
    evidence_items = await db.evidence.find({"case_id": case_id}).to_list(100)
    custody_entries = await db.chain_of_custody.find({"case_id": case_id}).sort("timestamp", 1).to_list(200)
    audit_logs = await db.audit_logs.find({"case_id": case_id}).sort("timestamp", -1).to_list(100)
    telemetry_count = await db.telemetry_events.count_documents({"case_id": case_id})

    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>TraceX Investigation Report - {case.get('case_number', case_id)}</title>
    <style>
        body {{ font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; margin: 40px; color: #1e293b; background: #fff; line-height: 1.5; }}
        h1, h2, h3 {{ color: #0f172a; border-bottom: 2px solid #e2e8f0; padding-bottom: 8px; }}
        .header {{ margin-bottom: 30px; }}
        .badge {{ background: #0284c7; color: white; padding: 4px 10px; border-radius: 4px; font-size: 12px; font-weight: bold; font-family: monospace; }}
        .meta-table, .data-table {{ width: 100%; border-collapse: collapse; margin-bottom: 30px; font-size: 13px; }}
        .meta-table td {{ padding: 8px 12px; border: 1px solid #cbd5e1; }}
        .meta-table td.label {{ background: #f8fafc; font-weight: bold; width: 25%; color: #475569; }}
        .data-table th {{ background: #0f172a; color: white; padding: 10px; text-align: left; }}
        .data-table td {{ padding: 8px 10px; border: 1px solid #e2e8f0; }}
        .data-table tr:nth-child(even) {{ background: #f8fafc; }}
        .hash {{ font-family: monospace; font-size: 11px; word-break: break-all; color: #0284c7; }}
        .footer {{ margin-top: 50px; font-size: 11px; color: #64748b; text-align: center; border-top: 1px solid #cbd5e1; padding-top: 15px; }}
    </style>
</head>
<body>
    <div class="header">
        <h1>PROJECT TRACEX — DIGITAL FORENSIC EXAMINATION REPORT</h1>
        <p><strong>Generated On:</strong> {now_str} | <strong>Authority:</strong> Institutional Forensic Lab | <strong>Generated By:</strong> {generated_by}</p>
    </div>

    <h2>1. Case Metadata</h2>
    <table class="meta-table">
        <tr>
            <td class="label">Case Number</td>
            <td><strong>{case.get('case_number', 'N/A')}</strong> (ID: {case['case_id']})</td>
            <td class="label">Status</td>
            <td><span class="badge">{case.get('status', 'OPEN')}</span></td>
        </tr>
        <tr>
            <td class="label">Case Title</td>
            <td colspan="3">{case.get('title', 'N/A')}</td>
        </tr>
        <tr>
            <td class="label">Lead Investigator</td>
            <td>{case.get('investigator', 'Unassigned')}</td>
            <td class="label">Opened Date</td>
            <td>{case.get('created_at', 'N/A')}</td>
        </tr>
        <tr>
            <td class="label">Scope / Warrant</td>
            <td colspan="3">{case.get('description', 'N/A')}</td>
        </tr>
    </table>

    <h2>2. Authorized Examination Devices ({len(devices)})</h2>
    <table class="data-table">
        <thead>
            <tr>
                <th>Device ID</th>
                <th>Model</th>
                <th>OS Version</th>
                <th>Status</th>
                <th>Registration Date</th>
            </tr>
        </thead>
        <tbody>
            {''.join(f"<tr><td class='hash'>{d['device_id']}</td><td>{d.get('device_model', 'N/A')}</td><td>Android {d.get('android_version', 'N/A')}</td><td>{d.get('status', 'ACTIVE')}</td><td>{d.get('registered_at', 'N/A')}</td></tr>" for d in devices) if devices else "<tr><td colspan='5'>No devices registered under this case.</td></tr>"}
        </tbody>
    </table>

    <h2>3. Evidence Vault Artifacts ({len(evidence_items)})</h2>
    <table class="data-table">
        <thead>
            <tr>
                <th>Evidence ID</th>
                <th>Original Filename</th>
                <th>Size (Bytes)</th>
                <th>SHA-256 Cryptographic Checksum</th>
                <th>Acquired Timestamp</th>
            </tr>
        </thead>
        <tbody>
            {''.join(f"<tr><td><strong>{e['evidence_id']}</strong></td><td>{e['original_filename']}</td><td>{e['file_size']}</td><td class='hash'>{e['sha256']}</td><td>{e['uploaded_at']}</td></tr>" for e in evidence_items) if evidence_items else "<tr><td colspan='5'>No evidence files secured.</td></tr>"}
        </tbody>
    </table>

    <h2>4. Cryptographic Chain of Custody Ledger ({len(custody_entries)})</h2>
    <table class="data-table">
        <thead>
            <tr>
                <th>Timestamp</th>
                <th>Evidence ID</th>
                <th>Action</th>
                <th>Actor</th>
                <th>Event Hash (SHA-256 Chained)</th>
            </tr>
        </thead>
        <tbody>
            {''.join(f"<tr><td>{c['timestamp']}</td><td>{c['evidence_id']}</td><td><strong>{c['action']}</strong></td><td>{c['actor']}</td><td class='hash'>{c['event_hash']}</td></tr>" for c in custody_entries) if custody_entries else "<tr><td colspan='5'>No custody events logged.</td></tr>"}
        </tbody>
    </table>

    <h2>5. Authorized Telemetry Summary</h2>
    <p>Total authorized location telemetry events recorded: <strong>{telemetry_count}</strong></p>

    <div class="footer">
        <p>This document is an authoritative digital forensics examination report generated by Project TraceX.<br>
        All evidence hashes and chain of custody entries are mathematically verifiable against the secure vault repository.</p>
    </div>
</body>
</html>
"""
    return html

generate_case_report_html = generate_html_report
